umur =  19

if umur < 2:
    print("Orang tersebut adalah bayi (baby).")
elif umur < 4:
    print("Orang tersebut adalah balita (toddler).")
elif umur < 13:
    print("Orang tersebut adalah anak-anak (kid).")
elif umur < 20:
    print("Orang tersebut adalah remaja (teenager).")
